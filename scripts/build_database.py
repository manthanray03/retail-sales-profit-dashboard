"""
build_database.py
-----------------
Loads the CSV files into a SQLite database, runs the data quality checks, then
runs the KPI analysis queries and saves the results.

Outputs
  retail.db                       SQLite database (not committed, rebuilt each run)
  outputs/<query_name>.csv        one file per analysis query
  outputs/analysis_results.md     all results as readable tables
  powerbi/expected_values.md      numbers the Power BI cards should show

Run:  python scripts/build_database.py
"""

import re
import sqlite3
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"
SQL_DIR = ROOT / "sql"
OUT_DIR = ROOT / "outputs"
DB_PATH = ROOT / "retail.db"

LOAD_ORDER = [
    "dim_date", "dim_store", "dim_department", "dim_channel",
    "fact_sales", "fact_store_day", "fact_service_desk", "fact_targets",
]


def read_named_queries(path: Path) -> list[tuple[str, str]]:
    """Split a .sql file into (name, sql) pairs using '-- name: <name>' markers."""
    text = path.read_text(encoding="utf-8")
    parts = re.split(r"^--\s*name:\s*(\w+)\s*$", text, flags=re.MULTILINE)
    # parts = [header, name1, sql1, name2, sql2, ...]
    return [(parts[i], parts[i + 1].strip()) for i in range(1, len(parts), 2)]


TWO_DECIMALS = ("_pct", "_pts", "_x", "per_labour_hour", "per_1000_transactions", "avg_basket",
                "handle_minutes")
KEY_COLUMNS = ("year", "month_num", "year_month", "day_of_week_num")


def fmt(value, column: str) -> str:
    """Readable number formatting for the markdown tables."""
    if pd.isna(value):
        return ""
    if isinstance(value, str):
        return value
    if column in KEY_COLUMNS or column.endswith("_id"):
        return str(int(value))
    if column.endswith(TWO_DECIMALS):
        return f"{value:,.2f}"
    if "labour_hours" in column:
        return f"{value:,.1f}"
    return f"{value:,.0f}"


def to_markdown(df: pd.DataFrame) -> str:
    header = "| " + " | ".join(df.columns) + " |"
    divider = "| " + " | ".join("---" for _ in df.columns) + " |"
    rows = ["| " + " | ".join(fmt(v, c) for v, c in zip(row, df.columns)) + " |"
            for row in df.itertuples(index=False)]
    return "\n".join([header, divider, *rows])


def load_csvs(con: sqlite3.Connection) -> None:
    for table in LOAD_ORDER:
        # keep_default_na=False keeps blank holiday_event values as '' instead of NULL
        df = pd.read_csv(DATA_DIR / f"{table}.csv", keep_default_na=False)
        df.to_sql(table, con, if_exists="append", index=False, chunksize=20_000)
        print(f"  loaded {table:<18} {len(df):>9,} rows")


def run_checks(con: sqlite3.Connection) -> bool:
    print("\nData quality checks")
    all_passed = True
    for name, sql in read_named_queries(SQL_DIR / "02_data_quality_checks.sql"):
        check_name, failures = con.execute(sql).fetchone()
        status = "PASS" if failures == 0 else "FAIL"
        all_passed &= failures == 0
        print(f"  [{status}] {check_name} (failures: {failures})")
    return all_passed


def run_analysis(con: sqlite3.Connection) -> dict[str, pd.DataFrame]:
    OUT_DIR.mkdir(exist_ok=True)
    results = {}
    sections = ["# Analysis results\n",
                "Generated by `scripts/build_database.py` from `sql/03_kpi_analysis.sql`. "
                "All figures come from the simulated dataset in `data/`.\n"]
    queries = read_named_queries(SQL_DIR / "03_kpi_analysis.sql")
    for name, sql in queries:
        df = pd.read_sql_query(sql, con)
        df.to_csv(OUT_DIR / f"{name}.csv", index=False)
        results[name] = df
        question = next((line.split("Q:", 1)[1].strip() for line in sql.splitlines()
                         if line.startswith("-- Q:")), "")
        sections += [f"\n## {name}\n", f"**{question}**\n", to_markdown(df), ""]
    (OUT_DIR / "analysis_results.md").write_text("\n".join(sections) + "\n", encoding="utf-8")
    print(f"\nSaved {len(queries)} analysis results to outputs/")
    return results


def write_expected_values(con: sqlite3.Connection, results: dict[str, pd.DataFrame]) -> None:
    """Card values to compare against the Power BI report, one column per Year slicer value."""
    ops = pd.read_sql_query(
        """
        WITH s AS (SELECT d.year, SUM(f.net_sales) AS net_sales
                   FROM fact_sales f JOIN dim_date d ON d.date = f.date GROUP BY d.year),
             o AS (SELECT d.year, SUM(customer_transactions) AS txns, SUM(labour_hours) AS hours
                   FROM fact_store_day sd JOIN dim_date d ON d.date = sd.date GROUP BY d.year),
             n AS (SELECT d.year,
                          SUM(CASE WHEN c.channel_group = 'Online' THEN f.net_sales END) AS online
                   FROM fact_sales f
                   JOIN dim_date d ON d.date = f.date
                   JOIN dim_channel c ON c.channel_id = f.channel_id
                   GROUP BY d.year)
        SELECT s.year, s.net_sales / o.txns AS basket, s.net_sales / o.hours AS splh,
               o.txns, 100.0 * n.online / s.net_sales AS online_share
        FROM s JOIN o ON o.year = s.year JOIN n ON n.year = s.year ORDER BY s.year
        """,
        con,
    ).set_index("year")
    y = results["yearly_kpis"].set_index("year")
    desk = results["service_desk_yearly"].set_index("year")

    def money_m(v):
        return f"${v / 1e6:,.1f}M"

    def pct(v):
        return "" if pd.isna(v) else f"{v:.1f}%"

    rows = [
        ("Net Sales", lambda yr: money_m(y.at[yr, "net_sales"])),
        ("Net Sales YoY %", lambda yr: pct(y.at[yr, "net_sales_yoy_pct"]) or "(blank, no prior year)"),
        ("Gross Profit", lambda yr: money_m(y.at[yr, "gross_profit"])),
        ("Gross Profit YoY %", lambda yr: pct(y.at[yr, "gross_profit_yoy_pct"]) or "(blank, no prior year)"),
        ("Gross Margin %", lambda yr: pct(y.at[yr, "gross_margin_pct"])),
        ("Gross Margin Change (pts)",
         lambda yr: "(blank, no prior year)" if pd.isna(y.at[yr, "margin_change_pts"])
         else f"{y.at[yr, 'margin_change_pts']:+.2f} pts"),
        ("Markdown Rate %", lambda yr: pct(y.at[yr, "markdown_rate_pct"])),
        ("Return Rate %", lambda yr: pct(y.at[yr, "return_rate_pct"])),
        ("Sales Target", lambda yr: money_m(y.at[yr, "sales_target"])),
        ("Target Attainment %", lambda yr: pct(y.at[yr, "target_attainment_pct"])),
        ("Online Share %", lambda yr: pct(ops.at[yr, "online_share"])),
        ("Customer Transactions", lambda yr: f"{ops.at[yr, 'txns'] / 1e6:,.2f}M"),
        ("Average Basket", lambda yr: f"${ops.at[yr, 'basket']:,.2f}"),
        ("Sales per Labour Hour", lambda yr: f"${ops.at[yr, 'splh']:,.2f}"),
        ("Desk Contacts", lambda yr: f"{desk.at[yr, 'contacts']:,.0f}"),
        ("First Contact Resolution %", lambda yr: pct(desk.at[yr, "first_contact_resolution_pct"])),
        ("Avg Handle Time (min)", lambda yr: f"{desk.at[yr, 'avg_handle_minutes']:.2f}"),
    ]
    years = list(y.index)
    lines = [
        "# Expected values (answer key)",
        "",
        "Use this to check the Power BI report after you build it. Set the **Year** slicer to each",
        "year, clear every other slicer, and the KPI cards should match the numbers below",
        "(small differences in the last decimal come from rounding/format settings).",
        "",
        "This file is regenerated by `python scripts/build_database.py`, so it always matches the data.",
        "",
        "| Measure | " + " | ".join(str(yr) for yr in years) + " |",
        "| --- | " + " | ".join("---" for _ in years) + " |",
    ]
    for label, fn in rows:
        lines.append(f"| {label} | " + " | ".join(fn(yr) for yr in years) + " |")
    lines += [
        "",
        "If a card is off:",
        "- **Everything is off by the same factor** → a relationship is missing or inactive (Model view).",
        "- **YoY or PY measures are blank** → dim_date is not marked as a date table, or the",
        "  relationship uses a text column instead of a Date column.",
        "- **Average Basket / Sales per Labour Hour change when you click a department** → the",
        "  measure is missing its REMOVEFILTERS on dim_department and dim_channel.",
    ]
    (ROOT / "powerbi").mkdir(exist_ok=True)
    (ROOT / "powerbi" / "expected_values.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Saved powerbi/expected_values.md")


def main() -> None:
    if DB_PATH.exists():
        DB_PATH.unlink()
    con = sqlite3.connect(DB_PATH)
    try:
        con.executescript((SQL_DIR / "01_schema.sql").read_text(encoding="utf-8"))
        con.execute("PRAGMA foreign_keys = ON")
        print("Loading CSV files into SQLite")
        load_csvs(con)
        con.commit()

        if not run_checks(con):
            print("\nData quality checks failed. Fix the data before building the report.")
            sys.exit(1)

        results = run_analysis(con)
        write_expected_values(con, results)
    finally:
        con.close()
    print(f"\nDone. Database: {DB_PATH.name}")


if __name__ == "__main__":
    main()
